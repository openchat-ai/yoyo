/** Field-match extras loop (tyb length/content gates). */
function emitExtras(asm, meta, extraPatches) {
  const extras = meta.extras || [];
  for (let i = 0; i < extras.length; i++) {
    const [tybOff, tybLen] = extras[i];
    asm.raw(0x81, 0xff, ...u32le(tybLen));
    const jne1 = asm.buf.length;
    asm.raw(0x0f, 0x85, 0, 0, 0, 0);
    asm.raw(0x50, 0x51, 0x57, 0x56);
    asm.raw(0xb9, ...u32le(tybLen));
    asm.raw(0x49, 0x8d, 0xbf, ...u32le(tybOff));
    asm.raw(0xf3, 0xa6);
    asm.raw(0x5e, 0x5f, 0x59, 0x58);
    const jne2 = asm.buf.length;
    asm.raw(0x0f, 0x85, 0, 0, 0, 0);
    const jmpE = asm.buf.length;
    asm.raw(0xe9, 0, 0, 0, 0);
    extraPatches.push([jne1, jne2, jmpE, i + 2]);
  }
  return asm;
}

