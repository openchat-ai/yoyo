  if (asm.labels.jae_parse1_fail_gd != null) asm.labels.ja_parse1_fail_gd = asm.labels.jae_parse1_fail_gd;
  if (asm.labels.jae_parse1_fail_gs != null) asm.labels.ja_parse1_fail_gs = asm.labels.jae_parse1_fail_gs;
