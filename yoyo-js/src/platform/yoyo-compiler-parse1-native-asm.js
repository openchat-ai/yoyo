/**
 * parse1 inc/dec: load slot, emit `mov rax,[r15+disp]; inc/dec rax; mov [r15+disp],rax`.
 * @param {'inc'|'dec'} kind
 */
function emitParse1IncDec(asm, kind) {
  const isInc = kind === 'inc';
  const lab = isInc ? 'parse1_inc_lbl' : 'parse1_dec_lbl';
  const failA = isInc ? 'jne_parse1_fail_ia' : 'jne_parse1_fail_da';
  const failS = isInc ? 'ja_parse1_fail_is' : 'ja_parse1_fail_ds';
  const jaeD32 = isInc ? 'jae_parse1_inc_d32' : 'jae_parse1_dec_d32';
  const d32Lab = isInc ? 'parse1_inc_d32_lbl' : 'parse1_dec_d32_lbl';
  const jmpAdv = isInc ? 'jmp_parse1_adv_i' : 'jmp_parse1_adv_d';
  const jmpAdv32 = isInc ? 'jmp_parse1_adv_i32' : 'jmp_parse1_adv_d32';
  const arithImm = isInc ? 0xc0 : 0xc8; // inc rax / dec rax

  asm.lab(lab);
  asm.raw(0x41, 0x80, 0x78, 0x01, 0x01); // argc==1
  asm.jccSite(failA, 0x85);
  asm.raw(0x41, 0x0f, 0xb7, 0x40, 0x02); // movzx eax, word [r8+2]
  asm.raw(0x3d, 0x00, 0x01, 0x00, 0x00); // cmp eax, 0x100
  asm.jccSite(failS, 0x83); // jae fail
  asm.raw(0xc1, 0xe0, 0x03); // shl eax, 3
  asm.raw(0x89, 0x44, 0x24, 0x58);
  asm.raw(0x81, 0x7c, 0x24, 0x58, 0x80, 0x00, 0x00, 0x00); // disp >= 0x80 → d32
  asm.jccSite(jaeD32, 0x83);
  // disp8 path: movabs rax, imm64 template then patch disp bytes
  asm.raw(0x48, 0xb8, 0x49, 0x8b, 0x47, 0x00, 0x48, 0xff, arithImm, 0x49);
  asm.raw(0x48, 0x89, 0x07);
  asm.raw(0x66, 0xc7, 0x47, 0x08, 0x89, 0x47);
  asm.raw(0xc6, 0x47, 0x0a, 0x00);
  asm.raw(0x8a, 0x44, 0x24, 0x58);
  asm.raw(0x88, 0x47, 0x03);
  asm.raw(0x88, 0x47, 0x0a);
  asm.raw(0x48, 0x83, 0xc7, 0x0b);
  asm.jmpSite(jmpAdv);

  asm.lab(d32Lab);
  asm.raw(0xc7, 0x07, 0x49, 0x8b, 0x87, 0x00);
  asm.raw(0x8b, 0x44, 0x24, 0x58);
  asm.raw(0x89, 0x47, 0x03);
  asm.raw(0xc7, 0x47, 0x07, 0x48, 0xff, arithImm, 0x49);
  asm.raw(0x66, 0xc7, 0x47, 0x0b, 0x89, 0x87);
  asm.raw(0x8b, 0x44, 0x24, 0x58);
  asm.raw(0x89, 0x47, 0x0d);
  asm.raw(0x48, 0x83, 0xc7, 0x11);
  asm.jmpSite(jmpAdv32);
  return asm;
}

