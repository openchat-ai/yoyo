/**
 * FX-2d native x64 builders for parse1 machine emit.
 * Hand-written encodings — not copied from pe_dll_link.rs text.
 * Growing rewrite target: replace lifted emit-all body with these builders.
 *
 * Prefix progress (unpatched bytes ≡ emitAll / dump):
 *   → parse1_ret_mid ≈ growing · cut=`emit1_nop`.
 *   Remaining lifted: emit1/emit2 / live2 seed stubs.
 */

function u32le(n) {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n >>> 0, 0);
  return [...b];
}

class CodeAsm {
  constructor() {
    this.buf = [];
    this.labels = Object.create(null);
    this.patches = []; // {kind, at:label|off, to:label}
  }
  raw(...bytes) {
    for (const b of bytes) this.buf.push(b & 0xff);
    return this;
  }
  lab(name) {
    this.labels[name] = this.buf.length;
    return this;
  }
  /** Emit jcc rel32 placeholder; site labeled `site`. Target patched later. */
  jccSite(site, op2) {
    this.lab(site);
    this.raw(0x0f, op2, 0, 0, 0, 0);
    return this;
  }
  jmpSite(site) {
    this.lab(site);
    this.raw(0xe9, 0, 0, 0, 0);
    return this;
  }
  patch(kind, at, to) {
    this.patches.push({ kind, at, to });
    return this;
  }
  applyPatches() {
    for (const p of this.patches) {
      const at = typeof p.at === 'number' ? p.at : this.labels[p.at];
      const to = this.labels[p.to];
      if (at == null) throw new Error(`missing patch at ${p.at}`);
      if (to == null) throw new Error(`missing patch to ${p.to}`);
      if (p.kind === 'jcc') {
        const rel = (to - (at + 6)) | 0;
        this.buf[at + 2] = rel & 0xff;
        this.buf[at + 3] = (rel >>> 8) & 0xff;
        this.buf[at + 4] = (rel >>> 16) & 0xff;
        this.buf[at + 5] = (rel >>> 24) & 0xff;
      } else {
        const rel = (to - (at + 5)) | 0;
        this.buf[at + 1] = rel & 0xff;
        this.buf[at + 2] = (rel >>> 8) & 0xff;
        this.buf[at + 3] = (rel >>> 16) & 0xff;
        this.buf[at + 4] = (rel >>> 24) & 0xff;
      }
    }
    return this;
  }
  toBuffer() {
    return Buffer.from(this.buf);
  }
}

function cmpEdiImm8(asm, imm) {
  asm.raw(0x83, 0xff, imm & 0xff);
}
function cmpTyb(asm) {
  asm.raw(0x81, 0x3e, 0x54, 0x59, 0x42, 0x00);
}
function cmpW(asm, off, imm) {
  asm.raw(0x66, 0x83, 0x7e, off & 0xff, imm & 0xff);
}
function cmpB(asm, off, imm) {
  asm.raw(0x80, 0x7e, off & 0xff, imm & 0xff);
}

/** Open input.tyb → VirtualAlloc → ReadFile → CloseHandle. */
function emitOpenReadClose(asm, meta) {
  asm.raw(0x48, 0x83, 0xec, 0x78);
  asm.raw(0x49, 0x8d, 0x8f, ...u32le(meta.input_off));
  asm.raw(0xba, 0x00, 0x00, 0x00, 0x80);
  asm.raw(0x45, 0x31, 0xc0, 0x45, 0x31, 0xc9);
  asm.raw(0xc7, 0x44, 0x24, 0x20, 0x03, 0x00, 0x00, 0x00);
  asm.raw(0x48, 0xc7, 0x44, 0x24, 0x28, 0x80, 0x00, 0x00, 0x00);
  asm.raw(0x48, 0xc7, 0x44, 0x24, 0x30, 0x00, 0x00, 0x00, 0x00);
  asm.raw(0x41, 0xff, 0x97, 0x08, 0x00, 0x00, 0x00); // CreateFileA
  asm.raw(0x48, 0x83, 0xf8, 0xff);
  asm.jccSite('je_no_input', 0x84);
  asm.raw(0x48, 0x89, 0xc3);

  asm.raw(0x31, 0xc9);
  asm.raw(0xba, 0x00, 0x80, 0x00, 0x00);
  asm.raw(0x41, 0xb8, 0x00, 0x30, 0x00, 0x00);
  asm.raw(0x41, 0xb9, 0x04, 0x00, 0x00, 0x00);
  asm.raw(0x41, 0xff, 0x97, 0x00, 0x00, 0x00, 0x00); // VirtualAlloc
  asm.raw(0x48, 0x85, 0xc0);
  asm.jccSite('je_fail_va', 0x84);
  asm.raw(0x48, 0x89, 0xc6);

  asm.raw(0x48, 0x89, 0xd9);
  asm.raw(0x48, 0x89, 0xf2);
  asm.raw(0x41, 0xb8, 0x00, 0x80, 0x00, 0x00);
  asm.raw(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  asm.raw(0x48, 0xc7, 0x44, 0x24, 0x20, 0x00, 0x00, 0x00, 0x00);
  asm.raw(0x41, 0xff, 0x97, 0x10, 0x00, 0x00, 0x00); // ReadFile
  asm.raw(0x85, 0xc0);
  asm.jccSite('je_fail_rd', 0x84);
  asm.raw(0x8b, 0x7c, 0x24, 0x40);

  asm.raw(0x48, 0x89, 0xd9);
  asm.raw(0x41, 0xff, 0x97, 0x20, 0x00, 0x00, 0x00); // CloseHandle
  return asm;
}

/** size==0x10 TYB / count1 / op FF → ret_pe → do_write */
function emitRetFastPath(asm, meta) {
  cmpEdiImm8(asm, 0x10);
  asm.jccSite('jne_try_sr', 0x85);
  cmpTyb(asm);
  asm.jccSite('jne_fail_ret_tyb', 0x85);
  cmpW(asm, 0x06, 0x01);
  asm.jccSite('jne_fail_ret_cnt', 0x85);
  cmpB(asm, 0x08, 0xff);
  asm.jccSite('jne_fail_ret_op', 0x85);
  asm.raw(0x49, 0x8d, 0x97, ...u32le(meta.ret_pe_off));
  asm.raw(0x41, 0xb8, ...u32le(meta.seed_len));
  asm.jmpSite('jmp_do_write');
  return asm;
}

