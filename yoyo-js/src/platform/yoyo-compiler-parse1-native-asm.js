/**
 * Full native parse1 code.bin body (incl. emit1/emit2/live2 stubs).
 * @param {object} seeds required (load/write bodies)
 */
function emitNativeFront(meta, seeds) {
  const asm = new CodeAsm();
  const extraPatches = [];
  emitOpenReadClose(asm, meta);
  emitRetFastPath(asm, meta);
  emitSetretFastPath(asm);
  emitLive2OpcodeGates(asm);
  emitSizedMultiOpGates(asm);
  emitExtras(asm, meta, extraPatches);
  emitParse1AnyAndIoStubs(asm, meta);
  emitParse1Setup(asm, meta);
  emitParse1OpcodeDispatch(asm);
  emitParse1Nop(asm);
  emitParse1IncDec(asm, 'inc');
  emitParse1IncDec(asm, 'dec');
  emitParse1Get(asm);
  emitParse1Set(asm);
  emitParse1AddSub(asm, 'add');
  emitParse1AddSub(asm, 'sub');
  emitParse1Cmp(asm);
  emitParse1Imul(asm);
  emitParse1Aluv(asm);
  emitParse1Rawb(asm);
  emitParse1Raws(asm);
  emitParse1Data(asm);
  emitParse1Label(asm);
  emitParse1JmpCall(asm);
  emitParse1Jcc(asm);
  emitParse1Ldb(asm);
  emitParse1Stb(asm);
  emitParse1Alloc(asm);
  if (!seeds || !seeds.load || !seeds.write) {
    throw new Error('emitNativeFront requires seeds.load / seeds.write');
  }
  emitParse1Load(asm, seeds);
  emitParse1Write(asm, seeds);
  emitParse1Mcpd(asm);
  emitParse1Mcps(asm);
  emitParse1Advance(asm);
  emitParse1RetAndPatch(asm);
  emitParse1GoWAndH00Scan(asm);
  emitParse1CompactAndGrow(asm, meta);
  emitParse1WideH00AndRetMid(asm, meta);
  // emit1/emit2/live2 live in sibling module (avoids cyclic load at parse time)
  require('./yoyo-compiler-parse1-emit-stubs').emitParse1EmitStubs(asm, meta);
  asm.extraPatches = extraPatches;
  return asm;
}

