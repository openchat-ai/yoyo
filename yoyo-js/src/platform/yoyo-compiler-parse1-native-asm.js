/** Embed seed body as movabs+store sequence (load/write file helpers). */
function emitSeedBody(asm, seed) {
  let off = 0;
  while (off + 8 <= seed.length) {
    asm.raw(0x48, 0xb8, ...seed.subarray(off, off + 8));
    if (off === 0) asm.raw(0x48, 0x89, 0x07);
    else if (off < 0x80) asm.raw(0x48, 0x89, 0x47, off);
    else asm.raw(0x48, 0x89, 0x87, ...u32le(off));
    off += 8;
  }
  while (off < seed.length) {
    asm.raw(0xc6, 0x87, ...u32le(off), seed[off]);
    off += 1;
  }
}

