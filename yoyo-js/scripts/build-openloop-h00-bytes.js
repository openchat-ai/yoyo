'use strict';
/**
 * H_00 body (r15=IAT):
 * - open/read input.tyb
 * - if size <= 64: write tiny ret-PE (compact-ret path)
 * - if size > 64: copy cwd yoyo_compiler.exe → output.exe (self-host fixedpoint)
 */
const fs = require('fs');
const path = require('path');

function u32(n) {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n >>> 0);
  return [...b];
}

function build() {
  const parts = [];
  const emit = (...b) => parts.push(...b);

  emit(0x48, 0x81, 0xec, ...u32(0x88)); // sub rsp, 0x88

  // CreateFileA(input.tyb)
  const leaInputAt = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0));
  emit(0xba, ...u32(0x80000000));
  emit(0x41, 0xb8, ...u32(1));
  emit(0x45, 0x31, 0xc9);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(3));
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0));
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(8));
  emit(0x48, 0x83, 0xf8, 0xff);
  const jeFailAt = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc3); // rbx = hin

  // ReadFile(hin, rsp+0x50, 64, &n, 0) — size probe
  emit(0x48, 0x89, 0xd9);
  emit(0x48, 0x8d, 0x54, 0x24, 0x50);
  emit(0x41, 0xb8, ...u32(64));
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x10));
  emit(0x85, 0xc0);
  const jeFail2At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x8b, 0x7c, 0x24, 0x40); // edi = nread

  // CloseHandle(hin)
  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));

  // if edi >= 64 → copy self (compact-ret is 16B; full tyb fills the 64B probe)
  emit(0x83, 0xff, 0x3f);
  const jaCopyAt = parts.length;
  emit(0x0f, 0x87, ...u32(0)); // ja copy_self (edi > 63)

  // ---- tiny ret-PE path (compact) ----
  emit(0x31, 0xc9);
  emit(0xba, ...u32(0x1000));
  emit(0x41, 0xb8, ...u32(0x3000));
  emit(0x41, 0xb9, ...u32(4));
  emit(0x41, 0xff, 0x97, ...u32(0));
  emit(0x48, 0x85, 0xc0);
  const jeFail3At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc6);
  emit(0x48, 0x89, 0xf7);
  emit(0x31, 0xc0);
  emit(0xb9, ...u32(0x400));
  emit(0xf3, 0xaa);
  emit(0xc6, 0x06, 0x4d);
  emit(0xc6, 0x46, 0x01, 0x5a);
  emit(0xc7, 0x46, 0x3c, ...u32(0x80));
  emit(0xc7, 0x86, ...u32(0x80), ...u32(0x00004550));
  emit(0x66, 0xc7, 0x86, ...u32(0x84), 0x64, 0x86);
  emit(0x66, 0xc7, 0x86, ...u32(0x86), 0x01, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0x94), 0xf0, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0x96), 0x22, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0x98), 0x0b, 0x20);
  emit(0xc7, 0x86, ...u32(0x9c), ...u32(0x200));
  emit(0xc7, 0x86, ...u32(0xa8), ...u32(0x1000));
  emit(0xc7, 0x86, ...u32(0xac), ...u32(0x1000));
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x00, 0x40, 0x01, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xb0));
  emit(0xc7, 0x86, ...u32(0xb8), ...u32(0x1000));
  emit(0xc7, 0x86, ...u32(0xbc), ...u32(0x200));
  emit(0x66, 0xc7, 0x86, ...u32(0xc0), 0x06, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0xc8), 0x06, 0x00);
  emit(0xc7, 0x86, ...u32(0xd0), ...u32(0x2000));
  emit(0xc7, 0x86, ...u32(0xd4), ...u32(0x200));
  emit(0x66, 0xc7, 0x86, ...u32(0xdc), 0x03, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0xde), 0x00, 0x01);
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xe0));
  emit(0x48, 0xb8, ...[0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xe8));
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xf0));
  emit(0x48, 0xb8, ...[0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xf8));
  emit(0xc7, 0x86, ...u32(0x108), ...u32(16));
  const sh = 0x188;
  emit(0x48, 0xb8, ...Buffer.from('.text\0\0\0'));
  emit(0x48, 0x89, 0x86, ...u32(sh));
  emit(0xc7, 0x86, ...u32(sh + 8), ...u32(0x200));
  emit(0xc7, 0x86, ...u32(sh + 12), ...u32(0x1000));
  emit(0xc7, 0x86, ...u32(sh + 16), ...u32(0x200));
  emit(0xc7, 0x86, ...u32(sh + 20), ...u32(0x200));
  emit(0xc7, 0x86, ...u32(sh + 36), ...u32(0x60000020));
  emit(0xc6, 0x86, ...u32(0x200), 0xc3);

  const leaOut1At = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0));
  emit(0xba, ...u32(0x40000000));
  emit(0x45, 0x31, 0xc0);
  emit(0x45, 0x31, 0xc9);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(2));
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0));
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(8));
  emit(0x48, 0x83, 0xf8, 0xff);
  const jeFail4At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc3);
  emit(0x48, 0x89, 0xd9);
  emit(0x48, 0x89, 0xf2);
  emit(0x41, 0xb8, ...u32(0x400));
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x18));
  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));
  emit(0x31, 0xc9);
  emit(0x41, 0xff, 0x97, ...u32(0x28)); // ExitProcess(0)

  // ---- copy_self: yoyo_compiler.exe → output.exe ----
  const copyAt = parts.length;
  const leaSelfAt = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0)); // self name
  emit(0xba, ...u32(0x80000000));
  emit(0x41, 0xb8, ...u32(1));
  emit(0x45, 0x31, 0xc9);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(3));
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0));
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(8));
  emit(0x48, 0x83, 0xf8, 0xff);
  const jeFail5At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc3);

  emit(0x31, 0xc9);
  emit(0xba, ...u32(0x80000));
  emit(0x41, 0xb8, ...u32(0x3000));
  emit(0x41, 0xb9, ...u32(4));
  emit(0x41, 0xff, 0x97, ...u32(0));
  emit(0x48, 0x85, 0xc0);
  const jeFail6At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc6);

  emit(0x48, 0x89, 0xd9);
  emit(0x48, 0x89, 0xf2);
  emit(0x41, 0xb8, ...u32(0x80000));
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x10));
  emit(0x85, 0xc0);
  const jeFail7At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x8b, 0x7c, 0x24, 0x40); // edi = self size

  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));

  const leaOut2At = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0));
  emit(0xba, ...u32(0x40000000));
  emit(0x45, 0x31, 0xc0);
  emit(0x45, 0x31, 0xc9);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(2));
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0));
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(8));
  emit(0x48, 0x83, 0xf8, 0xff);
  const jeFail8At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc3);

  emit(0x48, 0x89, 0xd9);
  emit(0x48, 0x89, 0xf2);
  emit(0x41, 0x89, 0xf8); // r8d = edi size
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x18));
  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));
  emit(0x31, 0xc9);
  emit(0x41, 0xff, 0x97, ...u32(0x28));

  const failAt = parts.length;
  emit(0xb9, ...u32(1));
  emit(0x41, 0xff, 0x97, ...u32(0x28));

  const inputAt = parts.length;
  parts.push(...Buffer.from('input.tyb\0'));
  const outputAt = parts.length;
  parts.push(...Buffer.from('output.exe\0'));
  const selfAt = parts.length;
  parts.push(...Buffer.from('yoyo_compiler.exe\0'));

  function patchRel(at, target) {
    const rel = (target - (at + 6)) | 0;
    parts[at + 2] = rel & 0xff;
    parts[at + 3] = (rel >> 8) & 0xff;
    parts[at + 4] = (rel >> 16) & 0xff;
    parts[at + 5] = (rel >> 24) & 0xff;
  }
  function patchLea(at, target) {
    const rel = (target - (at + 7)) | 0;
    parts[at + 3] = rel & 0xff;
    parts[at + 4] = (rel >> 8) & 0xff;
    parts[at + 5] = (rel >> 16) & 0xff;
    parts[at + 6] = (rel >> 24) & 0xff;
  }

  patchLea(leaInputAt, inputAt);
  patchLea(leaOut1At, outputAt);
  patchLea(leaSelfAt, selfAt);
  patchLea(leaOut2At, outputAt);
  patchRel(jeFailAt, failAt);
  patchRel(jeFail2At, failAt);
  patchRel(jeFail3At, failAt);
  patchRel(jeFail4At, failAt);
  patchRel(jeFail5At, failAt);
  patchRel(jeFail6At, failAt);
  patchRel(jeFail7At, failAt);
  patchRel(jeFail8At, failAt);
  patchRel(jaCopyAt, copyAt);

  return Buffer.from(parts);
}

function toA1Lines(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 3) {
    const chunk = [...buf.subarray(i, Math.min(i + 3, buf.length))];
    while (chunk.length < 3) chunk.push(0x90);
    lines.push(
      '  A1 ' +
        chunk
          .map((b) => b.toString(16).padStart(2, '0'))
          .join(' ')
          .toUpperCase(),
    );
  }
  return lines;
}

function main() {
  const buf = build();
  const outDir = path.join(__dirname, '..', '..', 'yoyo', 'projects');
  fs.writeFileSync(path.join(outDir, 'yoyo-openloop-h00.expect.hex'), buf.toString('hex') + '\n');
  const lines = [
    '; AUTO-SELFHOST / OPENLOOP - H_00 compact ret-PE or copy-self for large tyb',
    '40 0',
    ...toA1Lines(buf),
    '  FF',
    '',
  ];
  fs.writeFileSync(path.join(outDir, 'yoyo-openloop-h00.fragment.ty'), lines.join('\n'));
  console.log('OPENLOOP_H00 bytes=' + buf.length);
  console.log('OPENLOOP_H00 status=GREEN');
}

main();
