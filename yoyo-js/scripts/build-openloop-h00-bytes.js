'use strict';
/**
 * Build compact x64 open-loop body for product H_00 (r15 = IAT already).
 * Opens input.tyb, reads, builds tiny ret PE in VirtualAlloc, writes output.exe.
 */
const fs = require('fs');
const path = require('path');

function u32(n) {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n >>> 0);
  return [...b];
}

function build() {
  const parts = [];
  const emit = (...bytes) => parts.push(...bytes);

  // sub rsp, 0x88
  emit(0x48, 0x81, 0xec, ...u32(0x88));

  // lea rcx, [rip+input_path]  ; patched after layout
  const leaInputAt = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0)); // disp32 placeholder

  // CreateFileA(path, GENERIC_READ=0x80000000, FILE_SHARE_READ=1, 0, OPEN_EXISTING=3, 0, 0)
  emit(0xba, ...u32(0x80000000)); // edx
  emit(0x41, 0xb8, ...u32(1)); // r8d = share
  emit(0x45, 0x31, 0xc9); // r9d = 0
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(3)); // disposition
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0)); // flags
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0)); // template
  emit(0x41, 0xff, 0x97, ...u32(8)); // call [r15+8] CreateFileA
  emit(0x48, 0x83, 0xf8, 0xff); // cmp rax, -1
  const jeFail1At = parts.length;
  emit(0x0f, 0x84, ...u32(0)); // je fail
  emit(0x48, 0x89, 0xc3); // mov rbx, rax  ; hin

  // ReadFile(hin, buf=rsp+0x50, 64, &read=rsp+0x40, 0)
  emit(0x48, 0x89, 0xd9); // mov rcx, rbx
  emit(0x48, 0x8d, 0x54, 0x24, 0x50); // lea rdx, [rsp+0x50]
  emit(0x41, 0xb8, ...u32(64)); // r8d
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40); // lea r9, [rsp+0x40]
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x10)); // ReadFile
  emit(0x85, 0xc0);
  const jeFail2At = parts.length;
  emit(0x0f, 0x84, ...u32(0));

  // CloseHandle(hin)
  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));

  // VirtualAlloc(0, 0x1000, MEM_COMMIT|RESERVE=0x3000, PAGE_READWRITE=4)
  emit(0x31, 0xc9);
  emit(0xba, ...u32(0x1000));
  emit(0x41, 0xb8, ...u32(0x3000));
  emit(0x41, 0xb9, ...u32(4));
  emit(0x41, 0xff, 0x97, ...u32(0)); // VirtualAlloc
  emit(0x48, 0x85, 0xc0);
  const jeFail3At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc6); // mov rsi, rax  ; pe buf

  // zero 0x400 bytes
  emit(0x48, 0x89, 0xf7); // mov rdi, rsi
  emit(0x31, 0xc0);
  emit(0xb9, ...u32(0x400));
  emit(0xf3, 0xaa);

  // MZ
  emit(0xc6, 0x06, 0x4d);
  emit(0xc6, 0x46, 0x01, 0x5a);
  emit(0xc7, 0x46, 0x3c, ...u32(0x80)); // e_lfanew

  // PE signature at +0x80
  emit(0xc7, 0x86, ...u32(0x80), ...u32(0x00004550));
  // Machine + NumberOfSections
  emit(0x66, 0xc7, 0x86, ...u32(0x84), 0x64, 0x86);
  emit(0x66, 0xc7, 0x86, ...u32(0x86), 0x01, 0x00);
  // SizeOfOptionalHeader=0xF0, Characteristics=0x22
  emit(0x66, 0xc7, 0x86, ...u32(0x94), 0xf0, 0x00);
  emit(0x66, 0xc7, 0x86, ...u32(0x96), 0x22, 0x00);
  // Optional magic PE32+
  emit(0x66, 0xc7, 0x86, ...u32(0x98), 0x0b, 0x20);
  // SizeOfCode=0x200
  emit(0xc7, 0x86, ...u32(0x9c), ...u32(0x200));
  // AddressOfEntryPoint=0x1000
  emit(0xc7, 0x86, ...u32(0xa8), ...u32(0x1000));
  // BaseOfCode=0x1000
  emit(0xc7, 0x86, ...u32(0xac), ...u32(0x1000));
  // ImageBase=0x140000000
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x00, 0x40, 0x01, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xb0));
  // SectionAlignment=0x1000, FileAlignment=0x200
  emit(0xc7, 0x86, ...u32(0xb8), ...u32(0x1000));
  emit(0xc7, 0x86, ...u32(0xbc), ...u32(0x200));
  // MajorOperatingSystemVersion=6
  emit(0x66, 0xc7, 0x86, ...u32(0xc0), 0x06, 0x00);
  // MajorSubsystemVersion=6
  emit(0x66, 0xc7, 0x86, ...u32(0xc8), 0x06, 0x00);
  // SizeOfImage=0x2000
  emit(0xc7, 0x86, ...u32(0xd0), ...u32(0x2000));
  // SizeOfHeaders=0x200
  emit(0xc7, 0x86, ...u32(0xd4), ...u32(0x200));
  // Subsystem=3 CONSOLE
  emit(0x66, 0xc7, 0x86, ...u32(0xdc), 0x03, 0x00);
  // DllCharacteristics=0x100 NX
  emit(0x66, 0xc7, 0x86, ...u32(0xde), 0x00, 0x01);
  // Stack reserve/commit
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xe0));
  emit(0x48, 0xb8, ...[0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xe8));
  emit(0x48, 0xb8, ...[0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xf0));
  emit(0x48, 0xb8, ...[0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
  emit(0x48, 0x89, 0x86, ...u32(0xf8));
  // NumberOfRvaAndSizes=16
  emit(0xc7, 0x86, ...u32(0x108), ...u32(16));

  // Section header at 0x80+4+20+0xF0 = 0x188
  const sh = 0x188;
  emit(0x48, 0xb8, ...Buffer.from('.text\0\0\0'));
  emit(0x48, 0x89, 0x86, ...u32(sh));
  emit(0xc7, 0x86, ...u32(sh + 8), ...u32(0x200)); // VirtualSize
  emit(0xc7, 0x86, ...u32(sh + 12), ...u32(0x1000)); // VA
  emit(0xc7, 0x86, ...u32(sh + 16), ...u32(0x200)); // SizeOfRawData
  emit(0xc7, 0x86, ...u32(sh + 20), ...u32(0x200)); // PointerToRawData
  emit(0xc7, 0x86, ...u32(sh + 36), ...u32(0x60000020)); // characteristics

  // code C3 at file offset 0x200
  emit(0xc6, 0x86, ...u32(0x200), 0xc3);

  // CreateFileA output.exe GENERIC_WRITE CREATE_ALWAYS
  const leaOutputAt = parts.length;
  emit(0x48, 0x8d, 0x0d, ...u32(0));
  emit(0xba, ...u32(0x40000000)); // GENERIC_WRITE
  emit(0x45, 0x31, 0xc0); // r8=0 share
  emit(0x45, 0x31, 0xc9); // r9=0
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(2)); // CREATE_ALWAYS
  emit(0x48, 0xc7, 0x44, 0x24, 0x28, ...u32(0));
  emit(0x48, 0xc7, 0x44, 0x24, 0x30, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(8));
  emit(0x48, 0x83, 0xf8, 0xff);
  const jeFail4At = parts.length;
  emit(0x0f, 0x84, ...u32(0));
  emit(0x48, 0x89, 0xc3); // hout

  // WriteFile(hout, buf, 0x400, &written, 0)
  emit(0x48, 0x89, 0xd9); // rcx
  emit(0x48, 0x89, 0xf2); // rdx = rsi
  emit(0x41, 0xb8, ...u32(0x400));
  emit(0x4c, 0x8d, 0x4c, 0x24, 0x40);
  emit(0x48, 0xc7, 0x44, 0x24, 0x20, ...u32(0));
  emit(0x41, 0xff, 0x97, ...u32(0x18)); // WriteFile

  // CloseHandle(hout)
  emit(0x48, 0x89, 0xd9);
  emit(0x41, 0xff, 0x97, ...u32(0x20));

  // ExitProcess(0)
  emit(0x31, 0xc9);
  emit(0x41, 0xff, 0x97, ...u32(0x28));

  const failAt = parts.length;
  emit(0xb9, ...u32(1));
  emit(0x41, 0xff, 0x97, ...u32(0x28)); // ExitProcess(1)

  // strings
  const inputAt = parts.length;
  const inputStr = Buffer.from('input.tyb\0');
  parts.push(...inputStr);
  const outputAt = parts.length;
  const outputStr = Buffer.from('output.exe\0');
  parts.push(...outputStr);

  function patchRel(at, target) {
    const next = at + 6; // length of 0f 84 xx xx xx xx OR for lea 7 bytes
    // detect opcode
    if (parts[at] === 0x0f && parts[at + 1] === 0x84) {
      const rel = target - (at + 6);
      parts[at + 2] = rel & 0xff;
      parts[at + 3] = (rel >> 8) & 0xff;
      parts[at + 4] = (rel >> 16) & 0xff;
      parts[at + 5] = (rel >> 24) & 0xff;
    }
  }
  function patchLea(at, target) {
    const rel = target - (at + 7);
    parts[at + 3] = rel & 0xff;
    parts[at + 4] = (rel >> 8) & 0xff;
    parts[at + 5] = (rel >> 16) & 0xff;
    parts[at + 6] = (rel >> 24) & 0xff;
  }

  patchLea(leaInputAt, inputAt);
  patchLea(leaOutputAt, outputAt);
  patchRel(jeFail1At, failAt);
  patchRel(jeFail2At, failAt);
  patchRel(jeFail3At, failAt);
  patchRel(jeFail4At, failAt);

  return Buffer.from(parts);
}

function toA1Lines(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 3) {
    const chunk = [...buf.subarray(i, Math.min(i + 3, buf.length))];
    while (chunk.length < 3) chunk.push(0x90);
    lines.push(
      '  A1 ' +
        chunk
          .map((b) => b.toString(16).padStart(2, '0'))
          .join(' ')
          .toUpperCase(),
    );
  }
  return lines;
}

function main() {
  const buf = build();
  const outDir = path.join(__dirname, '..', '..', 'yoyo', 'projects');
  fs.writeFileSync(path.join(outDir, 'yoyo-openloop-h00.expect.hex'), buf.toString('hex') + '\n');
  const lines = [
    '; AUTO-OPENLOOP - H_00 real open/read/write ret-PE (kills relay ABSENT)',
    '40 0',
    ...toA1Lines(buf),
    '  FF',
    '',
  ];
  fs.writeFileSync(path.join(outDir, 'yoyo-openloop-h00.fragment.ty'), lines.join('\n'));
  console.log('OPENLOOP_H00 bytes=' + buf.length);
  console.log('OPENLOOP_H00 a1_lines=' + toA1Lines(buf).length);
  console.log('OPENLOOP_H00 status=GREEN');
}

main();
